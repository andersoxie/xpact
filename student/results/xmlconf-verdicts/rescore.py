"""Re-score the 2026-10-14 xmlconf baseline with the runner's verdict rules.

The weeks 1-2 runner `run_xmlconf_conformance.ps1` (never in git) expected
REJECT for `invalid` cases and ran cases that need external entities or
XML 1.1. This script takes the *same observations* it recorded
(`student/baseline/logs/xmlconf-results.tsv`) and scores them again with
`expectation()` / `load_catalog()` from `scripts/run_w3c_conformance.py`, the
runner used by Jenkins, then adds today's result of that runner per case.
Nothing is run again; no runner is changed.

Usage, from the repository root:
    python -I student/results/xmlconf-verdicts/rescore.py \
        --suite-dir build/validation-corpora/w3c-xml-20130923/xmlconf \
        --today build/benchmarks/w3c-xml-conformance/results.tsv
Writes `cases.tsv` and `summary.md` next to this script.
"""

import argparse
import csv
import importlib.util
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
RUNNER = REPO / "scripts" / "run_w3c_conformance.py"
BASELINE = REPO / "student" / "baseline" / "logs" / "xmlconf-results.tsv"
CRASH_MARKERS = ("system execution failed", "iolated")
TWO_COLUMNS = "|---|---|"


def load_runner():
    spec = importlib.util.spec_from_file_location("run_w3c_conformance", RUNNER)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def read_tsv(path: Path) -> list[dict]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def is_crash(row: dict) -> bool:
    return any(marker in row["message"] for marker in CRASH_MARKERS)


def classify(row: dict, case) -> str:
    """The baseline observation scored with the runner's rules."""
    if case is None:
        return "not in catalog"
    if case.skip_reason:
        return "skipped"
    if is_crash(row):
        return "crash"
    return "pass" if row["observed"].upper() == case.expected else "fail"


def score_rows(baseline: list[dict], cases: dict, today: dict) -> list[dict]:
    rows = []
    for row in baseline:
        case = cases.get(row["id"])
        rows.append({
            "id": row["id"],
            "type": row["type"],
            "entities": row["entities"] or "none",
            "observed_2026_10_14": row["observed"].upper(),
            "old_expected": row["expected"].upper(),
            "old_result": ("crash-" if is_crash(row) else "") + row["result"].lower(),
            "new_expected": case.expected if case else "",
            "skip_reason": case.skip_reason if case else "not in catalog",
            "new_result": classify(row, case),
            "today_finalized": today.get(("Finalized", row["id"]), "-"),
            "today_finalized_assertions": today.get(("FinalizedAssertions", row["id"]), "-"),
        })
    return rows


def table(header: str, separator: str, counts: Counter, fmt) -> list[str]:
    return [header, separator] + [fmt(key, value) for key, value in counts]


def summary_lines(rows: list[dict], cases: dict, today: dict) -> list[str]:
    old = Counter(r["old_result"].replace("crash-", "") for r in rows)
    new = Counter(r["new_result"] for r in rows)
    fails = [r for r in rows if r["old_result"].endswith("fail")]
    real = [r for r in rows if r["new_result"] in ("fail", "crash")]
    not_in_old = sorted(set(cases) - {r["id"] for r in rows})
    old_crashes = sum(r["old_result"].startswith("crash-") for r in rows)

    lines = [
        "# xmlconf verdict rules: the 2026-10-14 baseline re-scored",
        "",
        "Generated by [`rescore.py`](rescore.py); per case: [`cases.tsv`](cases.tsv).",
        "",
        "## 1. Old rules vs the runner's rules, same observations",
        "",
        f"The 2026-10-14 run observed {len(rows):,} cases (workbench `xpact.exe`, assertions on).",
        "",
        "| Score | Old rules (`run_xmlconf_conformance.ps1`) | Runner's rules (`run_w3c_conformance.py`) |",
        "|---|---|---|",
        f"| pass | {old['pass']:,} | {new['pass']:,} |",
        f"| fail | {old['fail']:,} | {new['fail']:,} |",
        f"| crash (counted separately) | not separated: {old_crashes} crashes inside pass/fail | {new['crash']:,} |",
        f"| skipped (out of profile) | 0 | {new['skipped']:,} |",
        f"| not in the catalog | 0 | {new['not in catalog']:,} |",
        f"| **total** | **{sum(old.values()):,}** | **{sum(new.values()):,}** |",
        "",
        f"## 2. Where the {len(fails):,} old failures go",
        "",
    ]
    lines += table("| Under the runner's rules | Cases |", TWO_COLUMNS,
                   Counter(r["new_result"] for r in fails).most_common(),
                   lambda k, v: f"| {k} | {v:,} |")
    lines += ["", "By catalog type (old result -> new result):", ""]
    by_type = Counter((r["type"], r["old_result"].replace("crash-", ""), r["new_result"]) for r in fails)
    lines += table("| Type | Old | New | Cases |", "|---|---|---|---|", sorted(by_type.items()),
                   lambda k, v: f"| {k[0]} | {k[1]} | {k[2]} | {v:,} |")
    lines += ["", "Why cases are skipped now:", ""]
    lines += table("| Reason | Cases |", TWO_COLUMNS,
                   Counter(r["skip_reason"] for r in rows if r["new_result"] == "skipped").most_common(),
                   lambda k, v: f"| {k} | {v:,} |")
    lines += ["", "## 3. The real problems of 2026-10-14 and today", "",
              f"Cases that fail or crash even under the runner's rules: **{len(real):,}**.", ""]
    real_kind = Counter((r["type"], r["observed_2026_10_14"], r["new_result"]) for r in real)
    lines += table("| Type | Observed 2026-10-14 | New result | Cases |", "|---|---|---|---|",
                   sorted(real_kind.items()), lambda k, v: f"| {k[0]} | {k[1]} | {k[2]} | {v:,} |")
    lines += ["", "Today (`run_w3c_conformance.py`, 2026-10-26) for those cases:", ""]
    real_today = Counter((r["today_finalized"], r["today_finalized_assertions"]) for r in real)
    lines += table("| `Finalized` | `FinalizedAssertions` | Cases |", "|---|---|---|",
                   real_today.most_common(), lambda k, v: f"| {k[0]} | {k[1]} | {v:,} |")
    lines += ["", "## 4. Catalog cases the old runner did not run", "",
              f"The catalog has {len(cases):,} cases; the old run had {len(rows):,}. "
              f"{len(not_in_old):,} were not in it:", ""]
    lines += table("| Runner's rule for them | Cases |", TWO_COLUMNS,
                   Counter(cases[i].skip_reason or "applicable" for i in not_in_old).most_common(),
                   lambda k, v: f"| {k} | {v:,} |")
    lines += ["", "## 5. Today's runner, for comparison", "",
              "`FinalizedAssertions`, all 2,585 catalog cases, 2026-10-26:", ""]
    lines += table("| Status | Cases |", TWO_COLUMNS,
                   Counter(s for (e, _), s in today.items() if e == "FinalizedAssertions").most_common(),
                   lambda k, v: f"| {k} | {v:,} |")
    return lines


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--suite-dir", type=Path, required=True)
    parser.add_argument("--today", type=Path, required=True, help="results.tsv of run_w3c_conformance.py")
    args = parser.parse_args()

    cases = {case.id: case for case in load_runner().load_catalog(args.suite_dir)}
    today = {(r["engine"], r["case_id"]): r["status"] for r in read_tsv(args.today)}
    rows = score_rows(read_tsv(BASELINE), cases, today)

    with (HERE / "cases.tsv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    lines = summary_lines(rows, cases, today)
    (HERE / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} cases scored; see summary.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
